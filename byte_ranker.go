package lane

// ByteRanker ranks bytes within [0, 255]; rarer bytes should have lower rank.
type ByteRanker [256]uint8

func (r ByteRanker) pickTwo(needle []byte) (int, int) {
	var bestF, bestL, nextI int
	var bestR, nextR uint16 = 256, 256

	for i := range needle {
		rank := uint16(r[needle[i]])
		if rank > bestR {
			if rank < nextR {
				nextR, nextI = rank, i
			}
		} else {
			if rank == bestR {
				bestL = i
			} else {
				nextR, nextI = bestR, bestL
				bestR, bestF, bestL = rank, i, i
			}
		}
	}

	if bestF < bestL {
		return bestF, bestL
	}
	return min(bestF, nextI), max(nextI, bestL)
}

